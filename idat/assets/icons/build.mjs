// Builds idat/core/icons/icons.json from allowlist.json (next to this file): our icon
// name → the icon's shapes, as published in the @iconify-json packages, unchanged.
// Only listed icons exist in the app. To add one: add a line to the allowlist, run
// `npm run build:icons`, commit both files.
//
// How icons are drawn (size, stroke width, fill) is up to <c-icon>, not this script: Lucide
// icons are marked as stroked, Simple Icons logos are filled (`filled` below).

import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { getIconData } from "@iconify/utils";

const require = createRequire(import.meta.url);

const SETS = {
  lucide: { filled: false },
  "simple-icons": { filled: true },
};

const allowlistFile = new URL("allowlist.json", import.meta.url);
const outFile = new URL("../../core/icons/icons.json", import.meta.url);
const allowlist = JSON.parse(await readFile(allowlistFile, "utf8"));

const icons = {};
const sources = {};
const errors = [];
const hidden = [];

for (const [set, entries] of Object.entries(allowlist)) {
  if (!SETS[set]) {
    errors.push(`unknown icon set "${set}" (known: ${Object.keys(SETS).join(", ")})`);
    continue;
  }
  const data = require(`@iconify-json/${set}/icons.json`);
  const { version } = require(`@iconify-json/${set}/package.json`);
  const { license } = require(`@iconify-json/${set}/info.json`);
  sources[set] = { package: `@iconify-json/${set}@${version}`, licence: license.spdx };

  for (const [name, source] of Object.entries(entries)) {
    const icon = getIconData(data, source); // resolves aliases
    if (name in icons) {
      errors.push(`"${name}" is listed twice`);
    } else if (!icon) {
      errors.push(`${set}: no icon "${source}" (for "${name}")`);
    } else {
      // Hidden: removed upstream, kept by Iconify for compatibility.
      if (icon.hidden) hidden.push(`${set}:${source}`);
      const { left = 0, top = 0, width, height } = icon;
      icons[name] = {
        body: icon.body,
        viewBox: `${left} ${top} ${width} ${height}`,
        filled: SETS[set].filled,
      };
    }
  }
}

if (errors.length) {
  console.error(`build:icons failed:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}
if (hidden.length) {
  console.warn(`build:icons: removed upstream, may disappear in a later version: ${hidden.join(", ")}`);
}

const output = {
  _comment:
    "Generated by `npm run build:icons` from idat/assets/icons/allowlist.json. Do not edit. " +
    "Brand logos remain trademarks of their owners.",
  sources,
  icons: Object.fromEntries(Object.entries(icons).sort(([a], [b]) => a.localeCompare(b))),
};
await writeFile(outFile, `${JSON.stringify(output, null, 2)}\n`);
console.log(`build:icons: ${Object.keys(icons).length} icons`);
